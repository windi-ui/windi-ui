import type { ColorsGenerator } from './colors';
import type { VariantsGenerator } from './variants';
import type { SizesGenerator } from './size';
import type { ComponentsGenerator } from './components/generator';

/**
 * The names a config registers, for typed component props, a safelist, a component gallery or a list of known
 * classes. Colors are sorted, since they follow the palettes of the theme; the others keep the order of the build.
 */
export interface Manifest {
	/** The prefix of the CSS variables. */
	prefix: string;
	/** The colors with a `c-*` class, sorted; each also has a `c-accent-*` class. */
	colors: string[];
	/** The variants, as the `v-*` classes. */
	variants: string[];
	/** The sizes, as the `s-*` classes. */
	sizes: string[];
	/** The components, such as `btn`. */
	components: string[];
	/** By variant, the colors of `colors` with an override of it, sorted; a variant without one is left out. */
	overrides: Record<string, string[]>;
}

export function createManifest(prefix: string, { colors, variants, sizes, components }: {
	colors: ColorsGenerator, variants: VariantsGenerator, sizes: SizesGenerator, components: ComponentsGenerator
}): Manifest {
	const all = colors.names();
	const names = all.filter(c => !(c.startsWith('accent-') && all.includes(c.slice(7)))).sort();
	const overrides = variants.names()
		.map(v => [v, variants.overrideColors(v).filter(c => names.includes(c)).sort()] as const)
		.filter(([, list]) => list.length);

	return {
		prefix,
		colors: names,
		variants: variants.names(),
		sizes: sizes.names(),
		components: components.names(),
		overrides: Object.fromEntries(overrides),
	};
}

const union = (names: string[]) => names.length ? names.map(n => `'${n.replace(/[\\']/g, '\\$&')}'`).join(' | ') : 'never';

/**
 * The declaration file of a manifest: the types `WindiUIColor`, `WindiUIVariant` and `WindiUISize`, as unions of its
 * names, for typed `color`, `variant` and `size` props.
 */
export function manifestTypes({ colors, variants, sizes }: Manifest) {
	return [
		'// Generated by WindiUI from the config. Do not edit.',
		`export type WindiUIColor = ${union(colors)};`,
		`export type WindiUIVariant = ${union(variants)};`,
		`export type WindiUISize = ${union(sizes)};`,
		'',
	].join('\n');
}
